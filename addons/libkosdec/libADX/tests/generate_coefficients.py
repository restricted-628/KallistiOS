"""Certify ADX Q12 profiles with exact rational intervals.
Original exact rational intervals; no SDK constants or transcendental library.
"""
from fractions import Fraction as F
from math import isqrt
from decimal import Decimal, localcontext
import argparse
import json
from pathlib import Path

RATES = (8000, 11025, 16000, 22050, 24000, 32000, 44100, 48000)


def add(a, b):
    return a[0] + b[0], a[1] + b[1]


def neg(a):
    return -a[1], -a[0]


def mul(a, b):
    v = [x * y for x in a for y in b]
    return min(v), max(v)


def div(a, b):
    assert b[0] > 0
    return mul(a, (1 / b[1], 1 / b[0]))


def sqrt_interval(a):
    assert a[0] >= 0
    unit = 10 ** 80
    lo = isqrt(a[0].numerator * unit * unit // a[0].denominator)
    hi = isqrt(a[1].numerator * unit * unit // a[1].denominator) + 1
    result = F(lo, unit), F(hi, unit)
    assert result[0] ** 2 <= a[0] and result[1] ** 2 >= a[1]
    return result


def atan_reciprocal(q, terms):
    # Alternating decreasing terms: the exact value lies between partial sums.
    total = sum((F((-1) ** k, (2 * k + 1) * q ** (2 * k + 1))
                 for k in range(terms)), F(0))
    other = total + F((-1) ** terms, (2 * terms + 1) * q ** (2 * terms + 1))
    return min(total, other), max(total, other)


def cosine_point(x):
    assert 0 < x < 4
    term, total = F(1), F(1)
    for k in range(1, 24):
        term *= -x * x / ((2 * k - 1) * (2 * k))
        total += term
    other = total + term * -x * x / (47 * 48)
    return min(total, other), max(total, other)


def decimal(x):
    with localcontext() as ctx:
        ctx.prec = 85
        return str(Decimal(x.numerator) / Decimal(x.denominator))


def certify(rate, cutoff=500):
    assert 1 <= rate <= 48000 and 0 <= 2*cutoff <= rate
    if cutoff == 0:
        return {"profile": {"rate": rate, "cutoff": cutoff}, "method": "Exact zero-cutoff limit", "q12": [{"value": 8192}, {"value": -4096}]}
    # Machin identity: pi = 16 atan(1/5) - 4 atan(1/239).
    pi = add(mul((F(16), F(16)), atan_reciprocal(5, 72)),
             neg(mul((F(4), F(4)), atan_reciprocal(239, 24))))
    angle = mul(pi, (F(2 * cutoff, rate), F(2 * cutoff, rate)))
    # Handle the exact Nyquist endpoint; otherwise the interval is inside (0,pi).
    if 2*cutoff == rate:
        cos = (F(-1), F(-1))
    else:
        assert angle[1] < pi[0]
        cos = cosine_point(angle[1])[0], cosine_point(angle[0])[1]
    root2 = sqrt_interval((F(2), F(2)))
    a = add(root2, neg(cos))
    b = add(root2, (F(-1), F(-1)))
    radicand = add(mul(a, a), neg(mul(b, b)))
    # Rationalized positive pole: b/(a+sqrt(a*a-b*b)).
    pole = div(b, add(a, sqrt_interval(radicand)))
    q = [mul(pole, (F(8192), F(8192))),
         mul(mul(pole, pole), (F(-4096), F(-4096)))]
    values = []
    result = {'profile': {'rate': rate, 'cutoff': cutoff},
              'method': 'Exact rational alternating-series and square-root intervals',
              'q12': []}
    for lo, hi in q:
        assert int(lo) == int(hi)
        values.append(int(lo))
        lower_integer = lo.numerator // lo.denominator
        assert hi < lower_integer + 1
        margin = min(lo - lower_integer, lower_integer + 1 - hi)
        result['q12'].append({'value': int(lo), 'lower': decimal(lo),
                              'upper': decimal(hi), 'width': decimal(hi - lo),
                              'integer_boundary_margin_lower_bound': decimal(margin)})
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--proof', type=Path, help='Optional detailed certificate output')
    args = parser.parse_args()
    results = [certify(rate) for rate in RATES]
    text = '/* Generated by generate_coefficients.py; exact rational interval certificates. */\n'
    text += 'static const struct { unsigned rate; int16_t q12[2]; } coefficients[] = {\n'
    for r in results:
        text += '    {%d, {%d, %d}},\n' % (r['profile']['rate'], *(q['value'] for q in r['q12']))
    text += '};\n'
    (Path(__file__).parent / 'coefficient_vectors.h').write_text(text)
    if args.proof:
        args.proof.write_text(json.dumps(results, indent=2) + '\n')
    print(json.dumps(results, indent=2))


if __name__ == '__main__':
    main()
