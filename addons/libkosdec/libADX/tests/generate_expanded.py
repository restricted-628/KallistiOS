"""Original multi-rate binary32 oracle vectors, independent of candidate calls."""
from pathlib import Path
import random
from generate_coefficients import RATES, certify
from generate_profiles import group


def samples(values):
    return '{' + ','.join(map(str, values)) + '}'


def main():
    text = '/* Generated by generate_expanded.py; exact rational binary32 oracle. */\n'
    text += 'static const struct { unsigned rate,cutoff; int16_t pcm[2][65]; int16_t loop[2][131]; } expanded[] = {\n'
    stress = []
    for rate, cutoff in ([(r,500) for r in RATES] +
                         [(1,0),(2,1),(8000,0),(8000,4000),(12345,123),(44100,499),
                          (44100,1000),(48000,1),(48000,24000),(9999,4999)]):
        coeff = tuple(q['value'] for q in certify(rate,cutoff)['q12'])
        pcm, loop = [], []
        for channel in range(2):
            history, decoded = [0, 0], []
            for frame in range(0, 65, 32):
                block = [0, channel + 1] + [(i*7 + frame//32*3 + channel*19) & 255 for i in range(2, 18)]
                out, history, _ = group(block, min(32, 65-frame), coeff, history)
                decoded.extend(out)
            pcm.append(decoded)
            history, decoded = [0, 0], []
            # Loop [32,65) twice, then release and finish. Full-group histories
            # include final compressed padding on the memory/stream reader path.
            for first, last in [(0, 65), (32, 65), (32, 65)]:
                for frame in range(first, last, 32):
                    block = [0, channel + 1] + [(i*7 + frame//32*3 + channel*19) & 255 for i in range(2, 18)]
                    out, history, _ = group(block, 32, coeff, history)
                    decoded.extend(out[:min(32, last-frame)])
            loop.append(decoded)
        text += '    {%d,%d, {%s}, {%s}},\n' % (rate, cutoff, ','.join(map(samples, pcm)), ','.join(map(samples, loop)))
        rng = random.Random(rate)
        for history, scale, frames in [([32767,-32768],32767,32), ([-32768,32767],32767,1),
                                        ([1,-1],0,31), ([0,0],123,32)]:
            block = [scale >> 8, scale & 255] + [rng.randrange(256) for _ in range(16)]
            out, final, clips = group(block, frames, coeff, history)
            stress.append('    {%d,%d,%d,%d,%s,%s,%s,%s},\n' %
                          (rate, cutoff, frames, clips, samples(block), samples(history), samples(final), samples(out)))
    text += '};\nstatic const struct { unsigned rate,cutoff,frames,clips; uint8_t block[18]; int16_t initial[2],final[2],pcm[32]; } stress_vectors[] = {\n'
    text += ''.join(stress) + '};\n'
    (Path(__file__).parent / 'expanded_vectors.h').write_text(text)


if __name__ == '__main__':
    main()
