"""Independent exact-rational binary32 RN-even + DN=1 ADX test oracle.
No candidate calls, host floating multiply/add, SDK tables or decoder code.
"""
from fractions import Fraction as F
from pathlib import Path
import random
import sys


def value(bits):
    sign = -1 if bits >> 31 else 1
    exp = (bits >> 23) & 255
    frac = bits & 0x7fffff
    assert exp != 255
    if exp == 0:
        return F(0)  # DN=1; no subnormal inputs reach native primitive.
    power = exp - 150
    return sign * F((1 << 23) | frac) * (F(2) ** power)


def rn32(x):
    if not x:
        return 0
    sign = 0x80000000 if x < 0 else 0
    x = abs(x)
    exponent = x.numerator.bit_length() - x.denominator.bit_length()
    if x < F(2) ** exponent:
        exponent -= 1
    assert exponent <= 127
    scaled = x * F(2) ** (23 - max(exponent, -126))
    n, rem = divmod(scaled.numerator, scaled.denominator)
    if 2 * rem > scaled.denominator or (2 * rem == scaled.denominator and n & 1):
        n += 1
    if exponent < -126:
        # RN may reach minimum normal; otherwise DN=1 flushes the result.
        return sign | (0x00800000 if n >= 1 << 23 else 0)
    if n == 1 << 24:
        n >>= 1
        exponent += 1
    assert exponent <= 127
    return sign | ((exponent + 127) << 23) | (n - (1 << 23))


def fmul(a, b):
    return rn32(value(a) * value(b))


def fmac(a, b, c):
    return rn32(value(a) * value(b) + value(c))


def pcm(bits):
    x = value(bits)
    if x >= 1 << 31:
        return 32767, 1
    if x <= -(1 << 31):
        return -32768, int(x < -(1 << 31))
    return int(x) // 65536, 0  # int truncates first; // is arithmetic high word.


def group(block, frames, coeff, history):
    c0, c1 = [rn32(F(x, 4096)) for x in coeff]
    h1, h2 = [rn32(F(x * 65536)) for x in history]
    scale = rn32(F(block[0] * 256 + block[1] + 1))
    samples, clips = [], 0
    for i in range(frames):
        n = (block[2 + i // 2] >> (0 if i & 1 else 4)) & 15
        if n >= 8:
            n -= 16
        t = fmul(c1, h2)
        t = fmac(c0, h1, t)
        t = fmac(scale, rn32(F(n * 65536)), t)
        sample, clip = pcm(t)
        samples.append(sample)
        clips += clip
        h2, h1 = h1, t
    return samples, [pcm(h1)[0], pcm(h2)[0]], clips


def main():
    histories = [[0, 0], [0, 0]]
    samples = [[], []]
    for group_index, frames in enumerate([32, 32, 1]):
        for ch in range(2):
            block = [0, ch + 1] + [(i * 7 + group_index * 3 + ch * 19) & 255 for i in range(2, 18)]
            out, histories[ch], clips = group(block, frames, (7334, -3283), histories[ch])
            assert clips == 0
            samples[ch].extend(out)
    text = '/* Generated by generate_profiles.py: independent rational float oracle. */\n'
    text += 'static const int16_t golden[2][65] = {\n'
    for ch in samples:
        text += '    {' + ','.join(map(str, ch)) + '},\n'
    text += '};\n'
    (Path(__file__).parent / 'profile_vectors.h').write_text(text)

if __name__ == '__main__':
    main()
