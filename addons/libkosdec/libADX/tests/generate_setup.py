"""Generate original Q12 decision tables with outward-rounded certificates.
No proprietary data. Runtime comparison is exact for integer rates <=48000.
"""
from fractions import Fraction as F
from math import isqrt, acos, pi as estimate_pi
from pathlib import Path
import json, time, argparse

from generate_coefficients import atan_reciprocal

BITS = 96
Q = 1 << BITS
D = 1 << 32
MAX_RATE = 48000

def ceildiv(n, d): return -((-n)//d)
def exact(n, d=1): return n*Q//d, ceildiv(n*Q, d)
def add(a,b): return a[0]+b[0],a[1]+b[1]
def neg(a): return -a[1],-a[0]
def mul(a,b):
    v=[x*y for x in a for y in b]
    return min(v)//Q,ceildiv(max(v),Q)
def div(a,b):
    assert b[0]>0
    v=[(x*Q,y) for x in a for y in b]
    return min(x//y for x,y in v),max(ceildiv(x,y) for x,y in v)
def sqrt(a):
    assert a[0]>=0
    return isqrt(a[0]*Q),isqrt(a[1]*Q)+1

lo5,hi5=atan_reciprocal(5,72);lo239,hi239=atan_reciprocal(239,24)
pilo,pihi=16*lo5-4*hi239,16*hi5-4*lo239
PI=(pilo.numerator*Q//pilo.denominator,ceildiv(pihi.numerator*Q,pihi.denominator))
ROOT2=sqrt(exact(2));B=add(ROOT2,exact(-1))

def cosine(n,d):
    assert 0<=2*n<=d
    if n==0:return exact(1)
    if 2*n==d:return exact(-1)
    x=mul(PI,exact(2*n,d));x2=mul(x,x)
    t=s=exact(1)
    for k in range(1,32):
        t=div(neg(mul(t,x2)),exact((2*k-1)*2*k));s=add(s,t)
    t=div(neg(mul(t,x2)),exact(63*64))
    error=max(abs(t[0]),abs(t[1]))
    return s[0]-error,s[1]+error

def boundary(c):
    return add(ROOT2,neg(mul(B,div(add(c,div(exact(1),c)),exact(2)))))

def quantized_pole_at_half():
    a=add(ROOT2,exact(1));c=div(B,add(a,sqrt(add(mul(a,a),neg(mul(B,B))))))
    v=[mul(c,exact(8192)),mul(mul(c,c),exact(4096))]
    assert all(x//Q==y//Q for x,y in v)
    return [x//Q for x,y in v]

def threshold(x):
    # libm only proposes a cell. Directed interval comparisons certify it.
    center=(x[0]+x[1])/(2*Q)
    k=int(acos(center)/(2*estimate_pi)*D)
    for attempt in range(8):
        left,right=cosine(k,D),cosine(k+1,D)
        if left[0]>x[1] and right[1]<x[0]:break
        if left[1]<x[0]:k-=1
        elif right[0]>x[1]:k+=1
        else:raise AssertionError(('cell precision insufficient',k,x,left,right))
    else:raise AssertionError('bad proposal')
    # Any distinct fractions with denominators <= MAX_RATE are separated by
    # >=1/MAX_RATE**2 >1/D. Thus at most one lies inside this cell.
    assert MAX_RATE**2<D
    candidate=F(2*k+1,2*D).limit_denominator(MAX_RATE)
    chosen=k+1; special=None
    if F(k,D)<candidate<F(k+1,D):
        value=cosine(candidate.numerator,candidate.denominator)
        if value[1]<x[0]:
            chosen=k  # fraction is above the true boundary
            assert F(k,D).denominator>MAX_RATE
        else:assert value[0]>x[1]  # fraction is below the true boundary
        special=[candidate.numerator,candidate.denominator,chosen==k]
    return chosen,special

def main():
    started=time.monotonic();minimum=quantized_pole_at_half();tables=[];specials=[]
    for which,maximum in [(0,8191),(1,4095)]:
        table=[]
        for n in range(maximum,minimum[which],-1):
            c=exact(n,8192) if which==0 else sqrt(exact(n,4096))
            k,s=threshold(boundary(c));table.append(k)
            if s:specials.append([which,n,*s])
        assert all(a<b for a,b in zip(table,table[1:]))
        tables.append(table)
        print(which,len(table),'elapsed',time.monotonic()-started,flush=True)
    out=dict(bits=BITS,ratio_bits=32,max_rate=MAX_RATE,minimum=minimum,tables=tables,specials=specials,elapsed_seconds=time.monotonic()-started)
    parser=argparse.ArgumentParser()
    parser.add_argument('--proof',type=Path)
    args=parser.parse_args()
    root=Path(__file__).resolve().parent
    text='/* Generated by tests/generate_setup.py; original certified Q32 boundaries. */\n'
    for name,table in zip(['first','second'],tables):
        text+='static const uint32_t setup_'+name+'[] = {\n'
        for start in range(0,len(table),8):
            text+='    '+','.join('UINT32_C(0x%08x)'%n for n in table[start:start+8])+',\n'
        text+='};\n'
    (root.parent/'src/adx_setup_table.h').write_text(text)
    text='/* Generated original near-boundary inputs, not SDK vectors. */\n'
    text+='static const struct { unsigned axis,cutoff,rate,expected; } setup_specials[] = {\n'
    for axis,n,num,den,above in specials:
        text+='    {%d,%d,%d,%d},\n'%(axis,num,den,n-int(above))
    text+='};\n'
    (root/'setup_specials.h').write_text(text)
    if args.proof:args.proof.write_text(json.dumps(out)+'\n')
    print('bytes',sum(map(len,tables))*4,'specials',len(specials),flush=True)

if __name__=='__main__':main()
