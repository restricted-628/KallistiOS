"""Encode observed stock request-to-final-TL behavior in the ADX request domain."""
import argparse
import csv


def ranges(path):
    with path.open(newline="", encoding="utf-8") as stream:
        rows = csv.DictReader(stream)
        if rows.fieldnames != ["tenths_db", "tl"]:
            raise ValueError("expected only tenths_db and tl")
        observations = []
        for expected, row in enumerate(rows, start=-999):
            if None in row or int(row["tenths_db"]) != expected or expected > 0:
                raise ValueError("expected one observation per request from -999 to 0")
            value = int(row["tl"])
            if not 0 <= value <= 255:
                raise ValueError("TL outside byte range")
            observations.append(value)
        if len(observations) != 1000:
            raise ValueError("incomplete effective request domain")

    prior = None
    for magnitude, value in enumerate(reversed(observations)):
        if value != prior:
            yield magnitude, value
            prior = value


def main():
    from pathlib import Path

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("observations", type=Path)
    args = parser.parse_args()
    print("/* Generated by tests/generate_legacy_gain.py from stock ADX behavior. */")
    print("static const struct { uint16_t first; uint8_t tl; } legacy_gain_ranges[] = {")
    for first, tl in ranges(args.observations):
        print(f"    {{{first}, {tl}}},")
    print("};")


if __name__ == "__main__":
    main()
