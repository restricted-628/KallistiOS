"""Pack observable binary32-angle/Q12 transitions for the rounded v3 setup.

Input is text containing three hex fields per line: argument bits and the
positive magnitudes of the two Q12 coefficients. Supply the zero row, then
only changing values in strictly ascending order.
"""
from pathlib import Path
import argparse


BLOCK = 32


def encode_delta(value):
    while value >= 128:
        yield (value & 127) | 128
        value >>= 7
    yield value


def pack(rows):
    chunks = []
    data = []
    for i in range(0, len(rows), BLOCK):
        angle, first, second = rows[i]
        if i >= BLOCK and rows[i - 1][0] >= angle:
            raise ValueError("angle words must increase")
        block = rows[i:i + BLOCK]
        chunks.append((angle, len(data), first, second, len(block) - 1))
        for word, a, b in block[1:]:
            x, y = a - first + 8, b - second + 8
            if word <= angle or not (0 <= x <= 15 and 0 <= y <= 15) or (x, y) == (8, 8):
                raise ValueError(f"invalid transition at {word:08x}")
            data.extend(encode_delta(word - angle))
            data.append(x << 4 | y)
            angle, first, second = word, a, b
    if len(data) > 65535:
        raise ValueError("transition offsets exceed the packed format")
    return chunks, data


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("transitions", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    rows = [tuple(int(word, 16) for word in line.split())
            for line in args.transitions.read_text().splitlines()]
    if not rows or rows[0] != (0, 8192, 4096):
        raise ValueError("expected unity-pole zero row")
    if not all(0 <= word <= 0x40490FDB and 0 <= a <= 8192 and 0 <= b <= 4096
               for word, a, b in rows):
        raise ValueError("transition outside the rounded argument or coefficient domain")
    chunks, data = pack(rows)
    with args.output.open("w") as out:
        print("/* Generated by tests/pack_rounded_setup.py. Numerical Q12 transitions. */", file=out)
        print("static const struct rounded_checkpoint rounded_checkpoints[] = {", file=out)
        for angle, offset, a, b, count in chunks:
            print(f"    {{0x{angle:08x}, {offset}, {a}, {b}, {count}}},", file=out)
        print("};\n\nstatic const uint8_t rounded_deltas[] = {", file=out)
        for i in range(0, len(data), 16):
            print("    " + ", ".join(f"0x{x:02x}" for x in data[i:i + 16]) + ",", file=out)
        print("};", file=out)
    print(f"{len(rows)} transitions, {len(chunks)} checkpoints, {len(data)} delta bytes")


if __name__ == "__main__":
    main()
