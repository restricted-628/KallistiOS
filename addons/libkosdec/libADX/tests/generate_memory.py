"""Carried whole-group histories and loop release: exact-rational test oracle."""
from pathlib import Path
from generate_profiles import group


def main():
    cases = [(0, 1), (0, 31), (0, 32), (0, 33), (32, 61), (32, 65)]
    text = '/* Generated by generate_memory.py; independent rational oracle. */\n'
    text += 'static const struct { unsigned start, end; int16_t pcm[2][131]; } vectors[] = {\n'
    for start, end in cases:
        output = [[], []]
        histories = [[0, 0], [0, 0]]
        # Initial prefix to end, one complete repeat, final repeat continuing EOF.
        for first, last in [(0, end), (start, end), (start, 65)]:
            for frame in range(first, last, 32):
                for ch in range(2):
                    block = [0, ch + 1] + [(i * 7 + frame // 32 * 3 + ch * 19) & 255 for i in range(2, 18)]
                    pcm, histories[ch], _ = group(block, 32, (7334, -3283), histories[ch])
                    output[ch].extend(pcm[:min(32, last - frame)])
        assert len(output[0]) == 65 + 2 * (end - start)
        text += '    {%d,%d, {\n' % (start, end)
        for samples in output:
            text += '        {' + ','.join(map(str, samples)) + '},\n'
        text += '    }},\n'
    text += '};\n'
    (Path(__file__).parent / 'memory_vectors.h').write_text(text)

if __name__ == '__main__':
    main()
