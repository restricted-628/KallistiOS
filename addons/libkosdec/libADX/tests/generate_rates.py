"""Original exact-rational 22050Hz PCM vectors; no candidate calls."""
from pathlib import Path
from generate_profiles import group
from generate_coefficients import certify


def main():
    coeff = tuple(q['value'] for q in certify(22050)['q12'])
    text = '/* Generated by generate_rates.py; independent rational binary32 oracle. */\n'
    text += 'static const struct { unsigned start, end; int16_t pcm[2][131]; } rate_vectors[] = {\n'
    for start, end in [(0, 1), (0, 31), (0, 32), (0, 33), (32, 61), (32, 65)]:
        output, histories = [[], []], [[0, 0], [0, 0]]
        for first, last in [(0, end), (start, end), (start, 65)]:
            for frame in range(first, last, 32):
                for ch in range(2):
                    block = [0, ch + 1] + [(i * 7 + frame // 32 * 3 + ch * 19) & 255 for i in range(2, 18)]
                    pcm, histories[ch], _ = group(block, 32, coeff, histories[ch])
                    output[ch].extend(pcm[:min(32, last - frame)])
        text += '    {%d,%d, {\n' % (start, end)
        for samples in output:
            text += '        {' + ','.join(map(str, samples)) + '},\n'
        text += '    }},\n'
    text += '};\nstatic const int16_t rate_golden[2][65] = {\n'
    for ch in range(2):
        samples, history = [], [0, 0]
        for g, frames in enumerate([32, 32, 1]):
            block = [0, ch + 1] + [(i * 7 + g * 3 + ch * 19) & 255 for i in range(2, 18)]
            out, history, _ = group(block, frames, coeff, history)
            samples.extend(out)
        text += '    {' + ','.join(map(str, samples)) + '},\n'
    text += '};\n'
    (Path(__file__).parent / 'rate_vectors.h').write_text(text)

if __name__ == '__main__':
    main()
