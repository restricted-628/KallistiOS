#!/usr/bin/env python3
"""Generate binary32 synthesis coefficients from MPEG equations and the PL_MPEG window."""
import math
from pathlib import Path
import re
import struct
import sys


def binary32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


def cosine(row, band):
    phase = ((16 + row) * (2 * band + 1)) % 128
    if phase in (32, 96):
        return 0.0
    return round(math.cos(math.pi * phase / 64), 9)


def floats(values, indent='    '):
    return [indent + ', '.join(binary32(value).hex() + 'f' for value in values[i:i + 4]) + ','
            for i in range(0, len(values), 4)]


def generate():
    reference = Path(__file__).resolve().parents[2] / 'libSFD' / 'src' / 'reference' / 'pl_mpeg.h'
    text = reference.read_text()
    source = re.search(r'PLM_AUDIO_SYNTHESIS_WINDOW\[\] = \{([^}]+)\}', text, re.S)[1]
    window = [float(value) for value in re.findall(r'[-+]?\d+(?:\.\d+)?', source)]
    assert len(window) == 512
    # PL_MPEG represents D scaled by 32768. Recover the ISO Table B.3
    # decimal precision, then scale to Q31 for the AHX PCM conversion.
    window = [round(value / 32768, 9) * (1 << 31) for value in window]
    yield '/* Generated by tools/generate_tables.py. MPEG synthesis window input from'
    yield '   PL_MPEG (MIT), Dominic Szablewski. See libSFD/src/reference/pl_mpeg.h. */'
    yield '#ifndef MEDIA_AHX_TABLES_H'
    yield '#define MEDIA_AHX_TABLES_H'
    levels = [0, 3, 5, 7, 9] + [(1 << width) - 1 for width in range(4, 15)]
    yield 'static const unsigned ahx_levels[16] = {'
    yield '    ' + ', '.join(str(level) for level in levels)
    yield '};'
    yield 'static const float ahx_gain[16] = {'
    yield from floats([0] + [2 / level for level in levels[1:]])
    yield '};'
    yield 'static const float ahx_bias[16] = {'
    yield from floats([0] + [binary32(1 / level) - 1 for level in levels[1:]])
    yield '};'
    yield 'static const float ahx_scale[64] = {'
    yield from floats([2 ** (1 - index / 3) for index in range(63)] + [1e-20])
    yield '};'
    yield 'static const float ahx_cosine[64][32] = {'
    for row in range(64):
        yield '    {'
        yield from floats([cosine(row, band) for band in range(32)], '        ')
        yield '    },'
    yield '};'
    yield 'static const float ahx_window[32][16] = {'
    for sample in range(32):
        yield '    {'
        yield from floats([window[32 * tap + sample] for tap in range(16)], '        ')
        yield '    },'
    yield '};'
    yield '#endif'


if __name__ == '__main__':
    sys.stdout.write('\n'.join(generate()) + '\n')
