/* Focused resident-frame cases, included by test.c to share its allocator and
   CRC fixture helpers. Generated bytes only; no external asset corpus. */
#include <xxhash.h>

#if defined(__has_feature)
#if __has_feature(address_sanitizer)
#define FRAME_ASAN 1
#endif
#endif
#if defined(__SANITIZE_ADDRESS__)
#define FRAME_ASAN 1
#endif
#ifdef FRAME_ASAN
#include <sanitizer/asan_interface.h>
#endif

static size_t frame_case_count;

static void frame_write32(uint8_t *p, uint32_t value) {
    for(unsigned i = 0; i < 4; ++i)
        p[i] = (uint8_t)(value >> (8 * i));
}

static uint32_t frame_read32(const uint8_t *p) {
    return (uint32_t)p[0] | (uint32_t)p[1] << 8 |
           (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24;
}

/* Unlike the large compressor fixture, this source allocation ends exactly at
   the advertised input end. The prefix permits misaligned borrowed pointers.
   Output has a canary on each side; ASan additionally makes the suffix
   unreadable/unwritable, including for an unsuccessful decode. */
static void frame_case(const char *name, pvr_chunk_asset_section_t section,
                       const pvr_chunk_asset_lz4_dictionary_t *dictionary,
                       const uint8_t *expected, size_t destination_bytes,
                       int expected_error, size_t source_offset,
                       size_t destination_offset) {
    size_t live_before = test_alloc_live;
    size_t source_allocation = source_offset + section.stored_bytes;
    uint8_t *source = malloc(source_allocation ? source_allocation : 1);
    size_t prefix = 1 + destination_offset;
    uint8_t *destination = malloc(prefix + destination_bytes + 1);
    uint8_t *out = destination + prefix;
    const void *original = section.stored_data;
    const size_t budgets[] = {1, 7, destination_bytes + 1};
    assert(source && destination);
    memset(source, 0xa5, source_allocation);
    memcpy(source + source_offset, original, section.stored_bytes);
    section.stored_data = source + source_offset;

    /* First synchronous, then three publication budgets. Only successful
       output must match: different budgets may expose different partial bytes
       before a checksum error, and failed output is never admitted. */
    for(size_t mode = 0; mode <= sizeof(budgets) / sizeof(budgets[0]); ++mode) {
        pvr_chunk_asset_lz4_state_t *state = NULL;
        pvr_chunk_asset_lz4_progress_t progress = {0};
        size_t calls = 0;
        int result, error;
        memset(destination, 0xa5, prefix + destination_bytes + 1);
#ifdef FRAME_ASAN
        __asan_poison_memory_region(out + destination_bytes, 1);
#endif
        errno = 0;
        if(mode == 0) {
            result = pvr_chunk_asset_lz4_decode(
                &section, out, destination_bytes, (void *)dictionary);
        }
        else {
            state = pvr_chunk_asset_lz4_state_create(
                &section, out, destination_bytes, dictionary);
            for(size_t i = 0; i < destination_bytes; ++i)
                assert(out[i] == 0xa5); /* preparation never publishes */
            result = -1;
            if(state) {
                size_t steps = 0;
                calls = test_alloc_calls;
                test_alloc_fail_at = calls + 1;
                do {
                    size_t previous_source = progress.source_bytes;
                    size_t previous_output = progress.output_bytes;
                    result = pvr_chunk_asset_lz4_state_step(state, budgets[mode - 1]);
                    error = errno;
                    assert(pvr_chunk_asset_lz4_state_get_progress(state, &progress) == 0);
                    assert(progress.source_bytes >= previous_source);
                    assert(progress.source_bytes <= section.stored_bytes);
                    assert(progress.output_bytes >= previous_output);
                    assert(progress.output_bytes <= destination_bytes);
                    assert(progress.output_bytes - previous_output <= budgets[mode - 1]);
                    assert(++steps <= section.stored_bytes + destination_bytes + 2);
                    if(result == PVR_CHUNK_ASSET_LZ4_MORE)
                        assert(progress.source_bytes != previous_source ||
                               progress.output_bytes != previous_output);
                    errno = error;
                } while(result == PVR_CHUNK_ASSET_LZ4_MORE);
                if(result == PVR_CHUNK_ASSET_LZ4_COMPLETE) {
                    assert(progress.complete);
                    assert(progress.source_bytes == section.stored_bytes);
                    assert(progress.output_bytes == section.decoded_bytes);
                    assert(pvr_chunk_asset_lz4_state_step(state, 1) ==
                           PVR_CHUNK_ASSET_LZ4_COMPLETE);
                    result = 0;
                }
                else {
                    assert(!progress.complete);
                    errno = 0;
                    assert(pvr_chunk_asset_lz4_state_step(state, 1) == -1);
                    assert(errno == error); /* terminal failure is sticky */
                }
                assert(test_alloc_calls == calls);
            }
        }
        error = result < 0 ? errno : 0;
        if(error != expected_error) {
            fprintf(stderr, "%s mode=%zu input=%zu output=%zu: errno=%d expected=%d\n",
                    name, mode, section.stored_bytes, destination_bytes,
                    error, expected_error);
            assert(error == expected_error);
        }
        if(!expected_error) {
            assert(result == 0);
            assert(!memcmp(out, expected, destination_bytes));
        }
        pvr_chunk_asset_lz4_state_destroy(state);
        if(mode && state)
            assert(test_alloc_calls == calls);
        test_alloc_fail_at = 0;
#ifdef FRAME_ASAN
        __asan_unpoison_memory_region(out + destination_bytes, 1);
#endif
        for(size_t i = 0; i < prefix; ++i)
            assert(destination[i] == 0xa5);
        assert(out[destination_bytes] == 0xa5);
        assert(!memcmp(source + source_offset, original, section.stored_bytes));
        for(size_t i = 0; i < source_offset; ++i)
            assert(source[i] == 0xa5);
    }
    free(destination);
    free(source);
    assert(test_alloc_live == live_before);
    ++frame_case_count;
}

static pvr_chunk_asset_section_t frame_fixture(
    uint8_t *frame, size_t capacity, const uint8_t *data, size_t size,
    bool linked, unsigned checksums, bool content_size,
    const pvr_chunk_asset_lz4_dictionary_t *dictionary) {
    LZ4F_preferences_t prefs = LZ4F_INIT_PREFERENCES;
    pvr_chunk_asset_section_t section = {0};
    LZ4F_cctx *context;
    LZ4F_CDict *cdict = NULL;
    size_t live_before = test_alloc_live;
    prefs.frameInfo.blockSizeID = LZ4F_max64KB;
    prefs.frameInfo.blockMode = linked ? LZ4F_blockLinked : LZ4F_blockIndependent;
    prefs.frameInfo.contentSize = content_size ? size : 0;
    prefs.frameInfo.blockChecksumFlag = (checksums & 1) ?
        LZ4F_blockChecksumEnabled : LZ4F_noBlockChecksum;
    prefs.frameInfo.contentChecksumFlag = (checksums & 2) ?
        LZ4F_contentChecksumEnabled : LZ4F_noContentChecksum;
    prefs.frameInfo.dictID = dictionary ? dictionary->id : 0;
    assert(!LZ4F_isError(LZ4F_createCompressionContext(&context, LZ4F_VERSION)));
    if(dictionary) {
        cdict = LZ4F_createCDict(dictionary->data, dictionary->size);
        assert(cdict);
    }
    section.stored_bytes = LZ4F_compressFrame_usingCDict(
        context, frame, capacity, data, size, cdict, &prefs);
    assert(!LZ4F_isError(section.stored_bytes));
    LZ4F_freeCDict(cdict);
    LZ4F_freeCompressionContext(context);
    assert(test_alloc_live == live_before);
    section.stored_data = frame;
    section.decoded_bytes = size;
    section.decoded_crc32 = checksum(data, size);
    section.dictionary_id = prefs.frameInfo.dictID;
    section.codec = PVR_CHUNK_ASSET_CODEC_LZ4_FRAME;
    return section;
}

static void frame_boundary_test(void) {
    uint8_t data[320], frame[1024], extended[2048];
    for(unsigned linked = 0; linked <= 1; ++linked) {
        for(unsigned raw = 0; raw <= 1; ++raw) {
            uint32_t random = 12345;
            for(size_t i = 0; i < sizeof(data); ++i) {
                random = random * UINT32_C(1664525) + UINT32_C(1013904223);
                data[i] = raw ? (uint8_t)(random >> 24) : (uint8_t)(i % 7);
            }
            for(unsigned flags = 0; flags < 4; ++flags) {
                pvr_chunk_asset_section_t section = frame_fixture(
                    frame, sizeof(frame), data, sizeof(data), linked, flags, true, NULL);
                size_t header = LZ4F_headerSize(frame, section.stored_bytes);
                assert(!LZ4F_isError(header));
                assert((frame_read32(frame + header) >> 31) == raw);
                frame_case("valid", section, NULL, data, sizeof(data), 0, 0, 0);
                for(size_t cut = 0; cut < section.stored_bytes; ++cut) {
                    pvr_chunk_asset_section_t bad = section;
                    bad.stored_bytes = cut;
                    frame_case("truncated", bad, NULL, NULL, sizeof(data),
                               cut ? EILSEQ : EINVAL, 1, 1);
                }
                pvr_chunk_asset_section_t bad = section;
                memcpy(extended, frame, section.stored_bytes);
                extended[section.stored_bytes] = 0xa5;
                bad.stored_data = extended;
                ++bad.stored_bytes;
                frame_case("trailing byte", bad, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
                memcpy(extended + section.stored_bytes, frame, section.stored_bytes);
                bad.stored_bytes = 2 * section.stored_bytes;
                frame_case("concatenated", bad, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
                bad = section;
                bad.decoded_crc32 ^= 1;
                frame_case("section CRC", bad, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
                frame[header - 1] ^= 1;
                frame_case("header checksum", section, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
                frame[header - 1] ^= 1;
                size_t block_end = header + 4 +
                    (frame_read32(frame + header) & UINT32_C(0x7fffffff));
                if(flags & 1) {
                    frame[block_end] ^= 1;
                    frame_case("block checksum", section, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
                    frame[block_end] ^= 1;
                    block_end += 4;
                }
                assert(frame_read32(frame + block_end) == 0); /* EndMark */
                if(flags & 2) {
                    frame[section.stored_bytes - 1] ^= 1;
                    frame_case("content checksum", section, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
                    frame[section.stored_bytes - 1] ^= 1;
                }
                /* Invalid advertised block payload length, with valid header. */
                uint32_t block = frame_read32(frame + header);
                frame_write32(frame + header, 65537);
                frame_case("oversized block", section, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
                frame_write32(frame + header, block);
                frame[header + 4] ^= 0x80;
                frame_case("damaged payload", section, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
                frame[header + 4] ^= 0x80;
            }
        }
    }
    uint8_t skip[8] = {0x50, 0x2a, 0x4d, 0x18, 0, 0, 0, 0};
    pvr_chunk_asset_section_t section = frame_fixture(
        frame, sizeof(frame), data, sizeof(data), false, 3, true, NULL);
    pvr_chunk_asset_section_t bad = section;
    bad.stored_data = skip;
    bad.stored_bytes = sizeof(skip);
    frame_case("skippable", bad, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
    memcpy(extended, frame, section.stored_bytes);
    memcpy(extended + section.stored_bytes, skip, sizeof(skip));
    bad.stored_data = extended;
    bad.stored_bytes = section.stored_bytes + sizeof(skip);
    frame_case("trailing skippable", bad, NULL, NULL, sizeof(data), EILSEQ, 0, 0);

    for(unsigned content_size = 0; content_size <= 1; ++content_size) {
        section = frame_fixture(frame, sizeof(frame), data, sizeof(data),
                                false, 0, content_size, NULL);
        frame_case("optional content size", section, NULL, data, sizeof(data), 0, 0, 0);
        for(int delta = -1; delta <= 1; delta += 2) {
            size_t length = (size_t)((int)sizeof(data) + delta);
            frame_case("destination length", section, NULL, NULL, length, EINVAL, 0, 0);
            bad = section;
            bad.decoded_bytes = length;
            frame_case("section length", bad, NULL, NULL, length, EILSEQ, 0, 0);
        }
        if(content_size) {
            /* Alter the 64-bit content-size field and repair only header HC. */
            size_t header = LZ4F_headerSize(frame, section.stored_bytes);
            frame[6] ^= 1;
            frame[header - 1] = (uint8_t)(XXH32(frame + 4, header - 5, 0) >> 8);
            frame_case("declared content length", section, NULL, NULL, sizeof(data), EILSEQ, 0, 0);
        }
    }
    /* A zero-length frame is valid for generic LZ4F but not a Compact section. */
    section = frame_fixture(frame, sizeof(frame), data, 0, false, 3, false, NULL);
    frame_case("empty section", section, NULL, NULL, 0, EINVAL, 0, 0);
    for(size_t size = 1; size <= 8; ++size) {
        section = frame_fixture(frame, sizeof(frame), data, size, false, 3, true, NULL);
        frame_case("tiny tails", section, NULL, data, size, 0, 1, 1);
    }
    /* All 32 offsets on both borrowed pointers, independently. */
    section = frame_fixture(frame, sizeof(frame), data, sizeof(data), false, 3, true, NULL);
    for(size_t src = 0; src < 32; ++src)
        for(size_t dst = 0; dst < 32; ++dst)
            frame_case("alignment", section, NULL, data, sizeof(data), 0, src, dst);
}

static void frame_multiblock_test(void) {
    uint8_t data[192], frame[1024];
    for(size_t i = 0; i < sizeof(data); ++i)
        data[i] = (uint8_t)(i % 47);
    for(unsigned linked = 0; linked <= 1; ++linked) {
        LZ4F_preferences_t prefs = LZ4F_INIT_PREFERENCES;
        LZ4F_cctx *context;
        prefs.frameInfo.blockSizeID = LZ4F_max64KB;
        prefs.frameInfo.blockMode = linked ? LZ4F_blockLinked : LZ4F_blockIndependent;
        prefs.frameInfo.contentSize = sizeof(data);
        prefs.frameInfo.blockChecksumFlag = LZ4F_blockChecksumEnabled;
        prefs.frameInfo.contentChecksumFlag = LZ4F_contentChecksumEnabled;
        prefs.autoFlush = 1;
        assert(!LZ4F_isError(LZ4F_createCompressionContext(&context, LZ4F_VERSION)));
        size_t bytes = LZ4F_compressBegin(context, frame, sizeof(frame), &prefs);
        assert(!LZ4F_isError(bytes));
        /* Explicit flushes create three small blocks without making the
           one-byte-budget truncation sweep depend on megabytes of output. */
        for(size_t offset = 0; offset < sizeof(data); offset += 64) {
            size_t added = LZ4F_compressUpdate(context, frame + bytes,
                sizeof(frame) - bytes, data + offset, 64, NULL);
            assert(!LZ4F_isError(added) && added > 0);
            bytes += added;
        }
        size_t added = LZ4F_compressEnd(context, frame + bytes, sizeof(frame) - bytes, NULL);
        assert(!LZ4F_isError(added));
        bytes += added;
        LZ4F_freeCompressionContext(context);
        size_t cursor = LZ4F_headerSize(frame, bytes), blocks = 0;
        while(frame_read32(frame + cursor)) {
            cursor += 8 + (frame_read32(frame + cursor) & UINT32_C(0x7fffffff));
            ++blocks;
            assert(cursor <= bytes - 8);
        }
        assert(blocks == 3 && cursor == bytes - 8);
        pvr_chunk_asset_section_t section = {0};
        section.stored_data = frame;
        section.stored_bytes = bytes;
        section.decoded_bytes = sizeof(data);
        section.decoded_crc32 = checksum(data, sizeof(data));
        section.codec = PVR_CHUNK_ASSET_CODEC_LZ4_FRAME;
        frame_case("three blocks", section, NULL, data, sizeof(data), 0, 1, 1);
        for(size_t cut = 0; cut < bytes; ++cut) {
            pvr_chunk_asset_section_t bad = section;
            bad.stored_bytes = cut;
            frame_case("three blocks truncated", bad, NULL, NULL, sizeof(data),
                       cut ? EILSEQ : EINVAL, 1, 1);
        }
    }
}

static void frame_dictionary_test(void) {
    uint8_t dictionary_data[1024], wrong_data[1024], data[256];
    uint8_t frame[1024], wrong_output[256];
    uint32_t random = 73;
    for(size_t i = 0; i < sizeof(dictionary_data); ++i) {
        random = random * UINT32_C(1664525) + UINT32_C(1013904223);
        dictionary_data[i] = (uint8_t)(random >> 24);
        wrong_data[i] = dictionary_data[i] ^ 0x80;
    }
    memcpy(data, dictionary_data + sizeof(dictionary_data) - sizeof(data), sizeof(data));
    pvr_chunk_asset_lz4_dictionary_t dictionary = {dictionary_data, sizeof(dictionary_data), 73};
    pvr_chunk_asset_lz4_dictionary_t wrong = {wrong_data, sizeof(wrong_data), 73};
    pvr_chunk_asset_section_t section = frame_fixture(
        frame, sizeof(frame), data, sizeof(data), false, 1, true, &dictionary);
    frame_case("dictionary valid", section, &dictionary, data, sizeof(data), 0, 0, 0);
    frame_case("dictionary missing", section, NULL, NULL, sizeof(data), ENOENT, 0, 0);
    wrong.id = 74;
    frame_case("caller dictionary ID", section, &wrong, NULL, sizeof(data), ENOENT, 0, 0);
    pvr_chunk_asset_section_t bad = section;
    bad.dictionary_id = 74;
    frame_case("frame dictionary ID", bad, &wrong, NULL, sizeof(data), EILSEQ, 0, 0);
    wrong.id = 73;

    /* A block checksum covers neither dictionary bytes nor decoded
       content. Prove this fixture actually references the dictionary, instead
       of assuming that a compressor used it or that every wrong byte matters. */
    LZ4F_dctx *context;
    size_t input_bytes = section.stored_bytes, output_bytes = sizeof(wrong_output);
    assert(!LZ4F_isError(LZ4F_createDecompressionContext(&context, LZ4F_VERSION)));
    assert(LZ4F_decompress_usingDict(context, wrong_output, &output_bytes,
        frame, &input_bytes, wrong.data, wrong.size, NULL) == 0);
    assert(input_bytes == section.stored_bytes && output_bytes == sizeof(data));
    assert(memcmp(wrong_output, data, sizeof(data)) != 0);
    LZ4F_freeDecompressionContext(context);
    frame_case("wrong dictionary section CRC", section, &wrong, NULL, sizeof(data), EILSEQ, 0, 0);
    bad = section;
    bad.decoded_crc32 = checksum(wrong_output, sizeof(wrong_output));
    frame_case("dictionary with matching section CRC", bad, &wrong, wrong_output, sizeof(data), 0, 0, 0);

    section = frame_fixture(frame, sizeof(frame), data, sizeof(data), false, 3, true, &dictionary);
    bad = section;
    bad.decoded_crc32 = checksum(wrong_output, sizeof(wrong_output));
    frame_case("wrong dictionary frame checksum", bad, &wrong, NULL, sizeof(data), EILSEQ, 0, 0);

    /* Three literals cannot contain a dictionary match. Same ID with unused,
       altered dictionary bytes is still a successful, CRC-correct decode. */
    section = frame_fixture(frame, sizeof(frame), data, 3, false, 3, true, &dictionary);
    frame_case("unused dictionary contents", section, &wrong, data, 3, 0, 0, 0);
    assert(test_alloc_live == 0);
}

static void frame_cases_test(void) {
    frame_boundary_test();
    frame_multiblock_test();
    frame_dictionary_test();
    printf("LZ4 frame boundary cases passed: %zu (sync and 3 step budgets each)\n",
           frame_case_count);
}
